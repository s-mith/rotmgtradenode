function itemUsableByClass(itemName: string, cls: string): boolean {
  const meta = ITEM_INDEX[normName(itemName)];
  if (!meta?.classes || !meta.slot) return false;
  return meta.classes.includes("ALL") || meta.classes.includes(cls);
}

