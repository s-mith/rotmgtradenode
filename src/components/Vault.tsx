// --- Material slider model -------------------------------------------------
// The dismantle sliders filter to items yielding at least X of each material.
// Steps snap to amounts that actually exist, and the sliders constrain each
// other so the selected thresholds always match at least one real item:
//   - mythical items carry no common/rare, so raising mythical clears both
//     (and raising common/rare clears mythical);
//   - common and rare are coupled, so raising one drops the other to the
//     highest amount some item still satisfies.

type MatKey = "common" | "rare" | "legendary" | "mythical";
export type MatFilter = Record<MatKey, number>;
// Low → high tier order; also the tie-break order when reducing sliders.
const MAT_ORDER: MatKey[] = ["common", "rare", "legendary", "mythical"];

// Every item's material yield as a dense vector (missing tier = 0).
const DISMANTLE_ITEMS = Object.values(ITEM_INDEX)
  .map((m) => m.dismantle)
  .filter((d): d is Dismantle => !!d)
  .map((d) => ({
    common: d.common ?? 0,
    rare: d.rare ?? 0,
    legendary: d.legendary ?? 0,
    mythical: d.mythical ?? 0,
  }));

// Snap steps for a material: 0 plus every distinct amount that exists, ascending.
const matSteps = (key: MatKey): number[] => {
  const s = new Set<number>([0]);
  for (const it of DISMANTLE_ITEMS) if (it[key] > 0) s.add(it[key]);
  return [...s].sort((a, b) => a - b);
};
const MAT_STEPS: Record<MatKey, number[]> = {
  common: matSteps("common"),
  rare: matSteps("rare"),
  legendary: matSteps("legendary"),
  mythical: matSteps("mythical"),
};

// True if some real item meets every material threshold at once.
const feasibleMat = (f: MatFilter) =>
  DISMANTLE_ITEMS.some((it) => MAT_ORDER.every((k) => it[k] >= f[k]));

const prevStep = (key: MatKey, v: number): number => {
  const steps = MAT_STEPS[key];
  const i = steps.indexOf(v);
  return i > 0 ? steps[i - 1] : 0;
};

// Smallest positive amount of `key` among `items` (0 if none carry it).
const floorPositive = (
  items: { common: number; rare: number; legendary: number; mythical: number }[],
  key: MatKey,
): number => {
  let min = Infinity;
  for (const it of items) if (it[key] > 0) min = Math.min(min, it[key]);
  return min === Infinity ? 0 : min;
};
// True if every item carries `key`.
const allHave = (
  items: { common: number; rare: number; legendary: number; mythical: number }[],
  key: MatKey,
): boolean => items.length > 0 && items.every((it) => it[key] > 0);

// After moving slider `moved`, adjust the common/rare/legendary sliders so the
// combination matches the items still visible, keeping the just-moved slider
// fixed. Using the forge tier order (common < rare < legendary):
//   - LOWER tiers snap to the floor amount those items share — the guaranteed
//     minimum you'd get (e.g. raising rare pulls common up to the tier's floor);
//   - a HIGHER tier engages only when EVERY visible item carries it (so raising
//     rare to the level where only the rare+legendary item remains lights up
//     legendary, but ordinary rare tiers leave it off);
//   - mythical is disjoint from all three, so touching it clears them (and vice
//     versa).
function reconcileMat(next: MatFilter, moved: MatKey): MatFilter {
  const r = { ...next };

  if (moved === "mythical") {
    if (r.mythical > 0) { r.common = 0; r.rare = 0; r.legendary = 0; }
    return r;
  }
  if (r.mythical > 0) r.mythical = 0; // engaging any other tier clears mythical

  const v = r[moved];
  if (v > 0) {
    const vis = DISMANTLE_ITEMS.filter((it) => it[moved] >= v);
    const movedTier = MAT_ORDER.indexOf(moved);
    for (const j of ["common", "rare", "legendary"] as const) {
      if (j === moved) continue;
      const lower = MAT_ORDER.indexOf(j) < movedTier;
      r[j] = lower || allHave(vis, j) ? floorPositive(vis, j) : 0;
    }
  }

  // Safety net: reduce the largest non-moved slider until the combo is real.
  let guard = 0;
  while (!feasibleMat(r) && guard++ < 40) {
    let pick: MatKey | null = null;
    for (const k of MAT_ORDER) {
      if (k === moved || r[k] <= 0) continue;
      if (pick === null || r[k] > r[pick]) pick = k;
    }
    if (pick === null) break;
    r[pick] = prevStep(pick, r[pick]);
  }
  return r;
}

// True if the item's dismantle yield meets every active material threshold.
// In exact mode the yield must equal the sliders on every tier, so "exactly 0"
// of everything selects items that don't dismantle at all.
function passesMaterials(itemName: string, f: MatFilter, exact: boolean): boolean {
  if (!exact && MAT_ORDER.every((k) => f[k] === 0)) return true;
  const d = itemDismantle(itemName);
  return MAT_ORDER.every((k) => (exact ? (d?.[k] ?? 0) === f[k] : (d?.[k] ?? 0) >= f[k]));
}

// Threshold check shared by the feed-power and enchant-slot filters: "at
// least" by default (0 = off), or "exactly" when the label has been toggled.
function passesMin(actual: number, min: number, exact: boolean): boolean {
  return exact ? actual === min : min === 0 || actual >= min;
}

