function TilePortalTip({
  hover,
  enchSprites,
}: {
  hover: { stack: Stack; rect: DOMRect };
  enchSprites: Map<number, string>;
}) {
  if (typeof document === "undefined") return null;
  const { stack, rect } = hover;
  const inst = stack.rep;
  // Anchor the tooltip just above the tile, centered horizontally. Done
  // via inline style because the position depends on viewport coords at
  // hover time — CSS can't express it.
  // Above the tile when there is room for the stat block, else below it.
  const above = rect.top > Math.min(420, window.innerHeight * 0.55);
  const style: React.CSSProperties = {
    position: "fixed",
    left: rect.left + rect.width / 2,
    top: above ? rect.top - 6 : rect.bottom + 6,
    transform: above ? "translate(-50%, -100%)" : "translate(-50%, 0)",
    zIndex: 1000,
    pointerEvents: "none",
  };
  return createPortal(
    <div className="pool-tile-tip pool-tile-tip-floating" style={style}>
      <div className="pool-tile-tip-name">{inst.itemName}</div>
      <div className={"pool-tile-tip-rarity rarity-" + inst.rarity}>{inst.rarity}</div>
      <ItemStats itemName={inst.itemName} enchantIds={stack.mixed ? [] : inst.enchantments.map((e) => e.id)} />
      <DismantleLine itemName={inst.itemName} />
      <FeedLine itemName={inst.itemName} />
      {stack.mixed && (
        <div className="pool-tile-tip-bot">mixed enchantments — stacked by rarity &amp; type</div>
      )}
      {!stack.mixed && inst.enchantments.length > 0 && (
        <ul className="pool-tile-tip-enchants">
          {inst.enchantments.map((e, i) => {
            const sprite = enchSprites.get(e.id);
            return (
              <li key={i}>
                {sprite && (
                  <img
                    className="pool-tile-tip-enchant-icon"
                    src={`data:image/png;base64,${sprite}`}
                    alt=""
                    aria-hidden="true"
                  />
                )}
                <span>{e.name ?? `Enchant #${e.id}`}</span>
              </li>
            );
          })}
        </ul>
      )}
      {stack.instances.length > 1 && (
        <div className="pool-tile-tip-bot">×{stack.instances.length} in pool</div>
      )}
      {stack.botIgns.length > 0 && (
        <div className="pool-tile-tip-bot">
          held by {stack.botIgns.slice(0, 4).join(", ")}
          {stack.botIgns.length > 4 ? ", …" : ""}
        </div>
      )}
    </div>,
    document.body,
  );
}

