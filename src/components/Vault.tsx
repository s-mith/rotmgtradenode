// Flat on-equip total of one stat for an item with the given enchantments.
// Items without tooltip data count as 0.
function statTotal(itemName: string, enchantIds: number[], which: StatSort): number {
  const t = ITEM_TOOLTIPS[normName(itemName)];
  if (!t) return 0;
  const totals = new Map<string, number>();
  for (const e of t.e ?? []) if (!e.r && !e.pct) totals.set(e.s, (totals.get(e.s) ?? 0) + e.v);
  for (const id of enchantIds) for (const e of ENCHANT_MODS[String(id)]?.e ?? []) totals.set(e.s, (totals.get(e.s) ?? 0) + e.v);
  return totals.get(which) ?? 0;
}
