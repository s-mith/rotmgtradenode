// Fold the instance's enchantments into the item's numbers. Returns the
// merged view plus which fields changed, so the card can highlight them.
function applyEnchants(t: ItemTooltip, enchantIds: number[]) {
  const mods = enchantIds.map((id) => ENCHANT_MODS[String(id)]).filter((m): m is EnchantMods => !!m);
  const stats = new Map<string, { base: number; bonus: number }>();
  for (const e of t.e ?? []) if (!e.r && !e.pct) stats.set(e.s, { base: e.v, bonus: 0 });
  let dmg: [number, number] = [1, 1], rof = 1, rng = 1, mp = 1, xp = 0;
  const lines: string[] = [];
  for (const m of mods) {
    for (const e of m.e ?? []) {
      const cur = stats.get(e.s) ?? { base: 0, bonus: 0 };
      cur.bonus += e.v;
      stats.set(e.s, cur);
    }
    if (m.dmg) dmg = [dmg[0] * m.dmg[0], dmg[1] * m.dmg[1]];
    if (m.rof) rof *= m.rof;
    if (m.rng) rng *= m.rng;
    if (m.mp) mp *= m.mp;
    if (m.xp) xp += m.xp;
    if (m.t) lines.push(m.t);
  }
  return { stats, dmg, rof, rng, mp, xp, lines, any: mods.length > 0 };
}
