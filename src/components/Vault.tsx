// Aggregate tile used in deposit mode. Same visual frame as PoolTile but
// shows a quantity badge instead of per-instance rarity (the bag of items
// may span multiple rarities/enchant sets — we don't render a single
// rarity color in that case, just the count). Non-interactive: deposit
// flow doesn't care which specific items go in.
const AggregateTile = memo(function AggregateTile({
  agg,
}: {
  agg: {
    itemId: string;
    itemName: string;
    sprite: string | null;
    rarity: Rarity;
    count: number;
    points: number;
    bots: string[];
  };
}) {
  // Title attribute is the simplest hover affordance — the per-instance
  // PoolTile uses a portaled rich tooltip for enchant icons, but in deposit
  // mode we're not surfacing enchants (the whole point is "any tier").
  const empty = agg.count === 0;
  const title =
    (empty
      ? `${agg.itemName} ×0 (accepted, but pool is out)`
      : `${agg.itemName} ×${agg.count}` +
        (agg.bots.length > 0 ? `\nheld by ${agg.bots.join(", ")}` : "")) +
    `\nworth ${agg.points} pt${agg.points === 1 ? "" : "s"} deposited (enchanted copies earn more)`;
  return (
    <div
      className={
        "pool-tile rarity-" + agg.rarity + " aggregate-tile" + (empty ? " aggregate-empty" : "")
      }
      title={title}
      aria-label={`${agg.itemName} ×${agg.count}, worth ${agg.points} point${agg.points === 1 ? "" : "s"}`}
    >
      <FitBadge className="points-badge" corner="tl">{agg.points}</FitBadge>
      <ItemSprite name={agg.itemName} />
      <FitBadge className="aggregate-count" corner="br">×{agg.count}</FitBadge>
    </div>
  );
});
